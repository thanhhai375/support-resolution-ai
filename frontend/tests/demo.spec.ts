import { expect, test } from '@playwright/test'

test('demo session works without any API requests and logout protects internal routes', async ({ page }) => {
  const apiRequests: string[] = []
  await page.route('**/api/**', route => { apiRequests.push(route.request().url()); return route.abort() })
  await page.goto('/tickets')
  await expect(page).toHaveURL('/login')
  await page.getByRole('button', { name: 'Điền tài khoản demo' }).click()
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).toHaveURL('/tickets')
  await expect(page.getByRole('button', { name: 'TK-1024', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'TK-1024', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Lịch sử trao đổi' })).toBeVisible()
  await page.getByRole('link', { name: 'Live Dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tổng quan hệ thống' })).toBeVisible()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phân tích hiệu suất hỗ trợ' })).toBeVisible()
  await page.reload()
  await expect(page).toHaveURL('/analytics')
  await page.getByRole('link', { name: 'AI Settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'AI Settings', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Logout' }).click()
  await expect(page).toHaveURL('/login')
  await page.goto('/dashboard')
  await expect(page).toHaveURL('/login')
  expect(apiRequests).toEqual([])
})

test('incorrect demo credentials do not start a session', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: 'Điền tài khoản demo' }).click()
  await page.getByLabel('Mật khẩu', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Email hoặc mật khẩu demo không đúng.')
  await expect(page).toHaveURL('/login')
})

test('knowledge search, product filters, pagination and source viewer', async ({ page }) => {
  await page.goto('/knowledge-base')
  await page.getByRole('button', { name: 'Điền tài khoản demo' }).click()
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.locator('p[role=status]')).toContainText('300 đoạn trích')
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Xem nguồn KB-013', exact: true })).toBeVisible()
  await page.getByLabel('Dòng sản phẩm').selectOption('Drives')
  await expect(page.locator('p[role=status]')).toContainText('150 đoạn trích')
  await expect(page.getByRole('button', { name: 'Xem nguồn KB-151', exact: true })).toBeVisible()
  await page.getByLabel('Tìm đoạn trích').fill('qua nhiet')
  await expect(page.locator('p[role=status]')).toContainText('25 đoạn trích')
  await page.getByRole('button', { name: 'Xem nguồn KB-151', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('Trang 12')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Xem nguồn KB-151', exact: true })).toBeFocused()
  await page.getByLabel('Tìm đoạn trích').fill('khong-ton-tai-xyz')
  await expect(page.getByRole('heading', { name: 'Không tìm thấy đoạn trích' })).toBeVisible()
  await page.getByRole('button', { name: 'Xóa bộ lọc' }).click()
  await expect(page.locator('p[role=status]')).toContainText('300 đoạn trích')
  await page.goto('/tickets')
  await page.getByRole('button', { name: 'TK-1024', exact: true }).click()
  await page.getByRole('button', { name: /Xem tài liệu nguồn/ }).first().click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Đóng', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/knowledge-base')
  await expect(page.getByRole('heading', { name: 'Kho tri thức kỹ thuật' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
